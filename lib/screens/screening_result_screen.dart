import 'package:flutter/material.dart';
import 'package:intl/intl.dart';
import 'package:share_plus/share_plus.dart';
import 'package:uuid/uuid.dart';
import '../data/database_helper.dart';
import '../models/patient_model.dart';
import '../models/questionnaire_model.dart';
import '../models/screening_result_model.dart';
import '../models/screening_session_model.dart';
import '../models/sensor_data_model.dart';
import '../theme/app_theme.dart';

class ScreeningResultScreen extends StatefulWidget {
  final Patient patient;
  final VitalsReading vitals;
  final SpirometrySummary spirometry;
  final AcousticSummary acoustic;
  final QuestionnaireResponse questionnaire;
  final RiskResult riskResult;

  const ScreeningResultScreen({
    super.key,
    required this.patient,
    required this.vitals,
    required this.spirometry,
    required this.acoustic,
    required this.questionnaire,
    required this.riskResult,
  });

  @override
  State<ScreeningResultScreen> createState() => _ScreeningResultScreenState();
}

class _ScreeningResultScreenState extends State<ScreeningResultScreen> {
  final _notesController = TextEditingController();
  bool _isSaved = false;
  bool _isSaving = false;

  Color get _riskColor {
    switch (widget.riskResult.riskLevel) {
      case RiskLevel.low:
        return AppTheme.riskLow;
      case RiskLevel.moderate:
        return AppTheme.riskModerate;
      case RiskLevel.high:
        return AppTheme.riskHigh;
      case RiskLevel.critical:
        return AppTheme.riskCritical;
    }
  }

  Future<void> _saveToDatabase() async {
    if (_isSaving || _isSaved) return;
    setState(() => _isSaving = true);

    final session = ScreeningSession(
      id: const Uuid().v4(),
      patientId: widget.patient.id,
      startedAt: DateTime.now(),
      completedAt: DateTime.now(),
      status: ScreeningStatus.completed,
      riskScore: widget.riskResult.riskScore,
      riskCategory: widget.riskResult.riskCategory,
      patient: widget.patient,
      vitals: widget.vitals,
      spirometry: widget.spirometry,
      acoustic: widget.acoustic,
      questionnaire: widget.questionnaire,
      riskResult: widget.riskResult,
      clinicalNotes: _notesController.text.trim(),
    );

    await DatabaseHelper.instance.insertScreening(session);
    setState(() {
      _isSaving = false;
      _isSaved = true;
    });

    if (mounted) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('Screening session saved to offline database!')),
      );
    }
  }

  void _shareReport() {
    final dateStr = DateFormat('yyyy-MM-dd HH:mm').format(DateTime.now());
    final r = widget.riskResult;
    final p = widget.patient;

    final buffer = StringBuffer();
    buffer.writeln('=== SWASTHAI CLINICAL SCREENING REPORT ===');
    buffer.writeln('Date: $dateStr');
    buffer.writeln('Patient: ${p.name} | Age: ${p.age} | Sex: ${p.gender.name.toUpperCase()}');
    buffer.writeln('Height: ${p.heightCm} cm | Weight: ${p.weightKg} kg (BMI: ${p.bmi.toStringAsFixed(1)})');
    buffer.writeln('------------------------------------------');
    buffer.writeln('OVERALL RISK LEVEL: ${r.riskLevel.label.toUpperCase()} (Score: ${r.overallScore}/100)');
    buffer.writeln('PATTERN: ${r.clinicalPattern.displayName}');
    buffer.writeln('------------------------------------------');
    buffer.writeln('KEY METRICS:');
    buffer.writeln('• Heart Rate: ${r.heartRate} bpm');
    buffer.writeln('• SpO2: ${r.spo2}%');
    buffer.writeln('• FEV1: ${r.fev1.toStringAsFixed(2)} L (${r.fev1PercentPredicted.toStringAsFixed(0)}% predicted)');
    buffer.writeln('• FVC: ${r.fvc.toStringAsFixed(2)} L (${r.fvcPercentPredicted.toStringAsFixed(0)}% predicted)');
    buffer.writeln('• FEV1/FVC: ${(r.fev1FvcRatio * 100).toStringAsFixed(1)}% (Ref: ≥70%)');
    buffer.writeln('• Peak Expiratory Flow: ${r.pefLpm.toStringAsFixed(0)} L/min');
    buffer.writeln('• Coughs in test: ${r.coughCount}');
    buffer.writeln('• Symptom Score: ${r.symptomScore}/30');
    buffer.writeln('------------------------------------------');
    buffer.writeln('CLINICAL RECOMMENDATIONS:');
    for (final rec in r.recommendations) {
      buffer.writeln('- $rec');
    }
    if (_notesController.text.isNotEmpty) {
      buffer.writeln('------------------------------------------');
      buffer.writeln('CLINICAL NOTES: ${_notesController.text.trim()}');
    }
    buffer.writeln('==========================================');
    buffer.writeln('Generated by SWASTHAI Point-of-Care System');

    // ignore: deprecated_member_use
    Share.share(buffer.toString(), subject: 'SWASTHAI Screening Report - ${p.name}');
  }

  @override
  Widget build(BuildContext context) {
    final r = widget.riskResult;
    final p = widget.patient;

    return Scaffold(
      appBar: AppBar(
        title: const Text('Screening Result', style: TextStyle(fontWeight: FontWeight.bold, fontSize: 18)),
        actions: [
          IconButton(
            icon: const Icon(Icons.share, color: AppTheme.textLight),
            tooltip: 'Share Report',
            onPressed: _shareReport,
          ),
        ],
      ),
      body: SingleChildScrollView(
        padding: const EdgeInsets.all(16),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            // Top Risk Hero Card
            Container(
              width: double.infinity,
              padding: const EdgeInsets.all(20),
              decoration: BoxDecoration(
                gradient: LinearGradient(
                  colors: [_riskColor.withAlpha(50), AppTheme.surfaceElevated],
                  begin: Alignment.topLeft,
                  end: Alignment.bottomRight,
                ),
                borderRadius: BorderRadius.circular(20),
                border: Border.all(color: _riskColor.withAlpha(90), width: 1.5),
              ),
              child: Column(
                children: [
                  Row(
                    mainAxisAlignment: MainAxisAlignment.spaceBetween,
                    children: [
                      Container(
                        padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 6),
                        decoration: BoxDecoration(
                          color: _riskColor,
                          borderRadius: BorderRadius.circular(20),
                        ),
                        child: Text(
                          r.riskLevel.label.toUpperCase(),
                          style: const TextStyle(fontWeight: FontWeight.bold, color: Colors.white, fontSize: 12),
                        ),
                      ),
                      Text(
                        'Score: ${r.overallScore}/100',
                        style: TextStyle(fontWeight: FontWeight.bold, color: _riskColor, fontSize: 16),
                      ),
                    ],
                  ),
                  const SizedBox(height: 16),
                  Text(
                    r.clinicalPattern.displayName,
                    textAlign: TextAlign.center,
                    style: const TextStyle(fontSize: 18, fontWeight: FontWeight.bold, color: AppTheme.textLight),
                  ),
                  if (r.emergencyFlag) ...[
                    const SizedBox(height: 12),
                    Container(
                      padding: const EdgeInsets.all(10),
                      decoration: BoxDecoration(
                        color: AppTheme.riskCritical.withAlpha(40),
                        borderRadius: BorderRadius.circular(10),
                      ),
                      child: const Row(
                        children: [
                          Icon(Icons.warning, color: AppTheme.riskCritical, size: 20),
                          SizedBox(width: 8),
                          Expanded(
                            child: Text(
                              'URGENT: Patient meets critical triage criteria (severe hypoxemia or airway compromise).',
                              style: TextStyle(color: Colors.white, fontSize: 12, fontWeight: FontWeight.w600),
                            ),
                          ),
                        ],
                      ),
                    ),
                  ],
                ],
              ),
            ),
            const SizedBox(height: 16),

            // Patient Summary Bar
            Container(
              padding: const EdgeInsets.all(14),
              decoration: BoxDecoration(
                color: AppTheme.surfaceElevated,
                borderRadius: BorderRadius.circular(14),
              ),
              child: Row(
                children: [
                  CircleAvatar(
                    backgroundColor: AppTheme.primaryTeal.withAlpha(30),
                    child: Text(p.name[0], style: const TextStyle(color: AppTheme.primaryTeal, fontWeight: FontWeight.bold)),
                  ),
                  const SizedBox(width: 12),
                  Expanded(
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        Text(p.name, style: const TextStyle(fontWeight: FontWeight.bold, color: AppTheme.textLight)),
                        Text(
                          '${p.age} yrs • ${p.gender.name.toUpperCase()} • ${p.heightCm} cm • BMI: ${p.bmi.toStringAsFixed(1)}',
                          style: const TextStyle(fontSize: 11, color: AppTheme.textMuted),
                        ),
                      ],
                    ),
                  ),
                ],
              ),
            ),
            const SizedBox(height: 16),

            // Metrics Matrix
            const Text('Cardiopulmonary & Spirometry Indices', style: TextStyle(fontSize: 15, fontWeight: FontWeight.bold, color: AppTheme.textLight)),
            const SizedBox(height: 10),
            Row(
              children: [
                _buildMetricBox('SpO2 Saturation', '${r.spo2}%', r.spo2 >= 95 ? 'Normal (≥95%)' : 'Subnormal', r.spo2 >= 95),
                const SizedBox(width: 10),
                _buildMetricBox('Heart Rate', '${r.heartRate} bpm', r.heartRate <= 100 && r.heartRate >= 60 ? 'Normal rhythm' : 'Irregular', r.heartRate <= 100 && r.heartRate >= 60),
              ],
            ),
            const SizedBox(height: 10),
            Row(
              children: [
                _buildMetricBox('FEV1 Volume', '${r.fev1.toStringAsFixed(2)} L', '${r.fev1PercentPredicted.toStringAsFixed(0)}% of pred', r.fev1PercentPredicted >= 80),
                const SizedBox(width: 10),
                _buildMetricBox('FVC Volume', '${r.fvc.toStringAsFixed(2)} L', '${r.fvcPercentPredicted.toStringAsFixed(0)}% of pred', r.fvcPercentPredicted >= 80),
              ],
            ),
            const SizedBox(height: 10),
            Row(
              children: [
                _buildMetricBox('FEV1 / FVC Ratio', '${(r.fev1FvcRatio * 100).toStringAsFixed(1)}%', r.fev1FvcRatio >= 0.70 ? 'Normal (≥70%)' : 'Airflow Obstruction', r.fev1FvcRatio >= 0.70),
                const SizedBox(width: 10),
                _buildMetricBox('Peak Flow (PEF)', '${r.pefLpm.toStringAsFixed(0)} L/m', '${r.pefPercentPredicted.toStringAsFixed(0)}% of pred', r.pefPercentPredicted >= 75),
              ],
            ),
            const SizedBox(height: 16),

            // Clinical Findings
            const Text('Clinical Findings Breakdown', style: TextStyle(fontSize: 15, fontWeight: FontWeight.bold, color: AppTheme.textLight)),
            const SizedBox(height: 8),
            Card(
              child: Padding(
                padding: const EdgeInsets.all(12),
                child: Column(
                  children: r.findings.map((f) {
                    return Padding(
                      padding: const EdgeInsets.symmetric(vertical: 6),
                      child: Row(
                        crossAxisAlignment: CrossAxisAlignment.start,
                        children: [
                          Icon(
                            f.isAbnormal ? Icons.error_outline : Icons.check_circle_outline,
                            color: f.isAbnormal ? (f.isUrgent ? AppTheme.riskCritical : AppTheme.riskModerate) : AppTheme.riskLow,
                            size: 18,
                          ),
                          const SizedBox(width: 10),
                          Expanded(
                            child: Column(
                              crossAxisAlignment: CrossAxisAlignment.start,
                              children: [
                                Text(
                                  f.title,
                                  style: TextStyle(
                                    fontSize: 13,
                                    fontWeight: FontWeight.w600,
                                    color: f.isAbnormal ? AppTheme.textLight : AppTheme.textMuted,
                                  ),
                                ),
                                const SizedBox(height: 2),
                                Text(f.details, style: const TextStyle(fontSize: 11, color: AppTheme.textMuted)),
                              ],
                            ),
                          ),
                        ],
                      ),
                    );
                  }).toList(),
                ),
              ),
            ),
            const SizedBox(height: 16),

            // Actionable Recommendations
            const Text('Actionable Clinical Recommendations', style: TextStyle(fontSize: 15, fontWeight: FontWeight.bold, color: AppTheme.textLight)),
            const SizedBox(height: 8),
            Card(
              child: Padding(
                padding: const EdgeInsets.all(14),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: r.recommendations.map((rec) {
                    return Padding(
                      padding: const EdgeInsets.symmetric(vertical: 4),
                      child: Row(
                        crossAxisAlignment: CrossAxisAlignment.start,
                        children: [
                          const Icon(Icons.arrow_right, color: AppTheme.primaryTeal, size: 20),
                          const SizedBox(width: 6),
                          Expanded(
                            child: Text(rec, style: const TextStyle(fontSize: 13, color: AppTheme.textLight, height: 1.3)),
                          ),
                        ],
                      ),
                    );
                  }).toList(),
                ),
              ),
            ),
            const SizedBox(height: 16),

            // Clinical Notes Field
            TextField(
              controller: _notesController,
              maxLines: 2,
              decoration: const InputDecoration(
                labelText: 'Healthcare Worker / Clinical Notes',
                hintText: 'Add clinical observations, medication prescribed, or referral details...',
              ),
            ),
            const SizedBox(height: 24),

            // Action Buttons
            Row(
              children: [
                Expanded(
                  child: ElevatedButton.icon(
                    onPressed: _isSaved ? null : _saveToDatabase,
                    icon: Icon(_isSaved ? Icons.check : Icons.save),
                    label: Text(_isSaved ? 'Saved to Offline DB' : 'Save to SQLite DB'),
                    style: ElevatedButton.styleFrom(
                      backgroundColor: _isSaved ? AppTheme.riskLow : AppTheme.primaryTeal,
                      padding: const EdgeInsets.symmetric(vertical: 14),
                    ),
                  ),
                ),
                const SizedBox(width: 12),
                Expanded(
                  child: OutlinedButton.icon(
                    onPressed: () {
                      Navigator.of(context).popUntil((route) => route.isFirst);
                    },
                    icon: const Icon(Icons.home),
                    label: const Text('Return Home'),
                    style: OutlinedButton.styleFrom(
                      padding: const EdgeInsets.symmetric(vertical: 14),
                    ),
                  ),
                ),
              ],
            ),
            const SizedBox(height: 24),
          ],
        ),
      ),
    );
  }

  Widget _buildMetricBox(String title, String val, String sub, bool isNormal) {
    return Expanded(
      child: Container(
        padding: const EdgeInsets.all(12),
        decoration: BoxDecoration(
          color: AppTheme.surfaceElevated,
          borderRadius: BorderRadius.circular(12),
          border: Border.all(color: isNormal ? Colors.white.withAlpha(10) : AppTheme.riskHigh.withAlpha(50)),
        ),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Text(title, style: const TextStyle(fontSize: 11, color: AppTheme.textMuted)),
            const SizedBox(height: 4),
            Text(val, style: const TextStyle(fontSize: 16, fontWeight: FontWeight.bold, color: AppTheme.textLight)),
            const SizedBox(height: 2),
            Text(
              sub,
              style: TextStyle(fontSize: 10, color: isNormal ? AppTheme.riskLow : AppTheme.riskHigh, fontWeight: FontWeight.w600),
            ),
          ],
        ),
      ),
    );
  }
}
